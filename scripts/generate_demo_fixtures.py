"""Generate original MIT demo fixtures without reference images or font files."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
GLYPHS = dict(zip(ALPHABET, (
    "75557 26227 71747 71317 55711 74717 74757 71122 75757 75717 "
    "25755 65656 34443 65556 74647 74644 34553 55755 72227 11152 55655 44447 "
    "57755 65555 25552 65644 25563 65655 34216 72222 55557 55552 55775 55255 55222 71247"
).split()))
GLYPHS.update({" ": "00000", ".": "00002"})


def sea():
    image = Image.new("RGB", (1000, 714))
    draw = ImageDraw.Draw(image)
    for y in range(714):
        if y < 330:
            color = (58 + y // 5, 66 + y // 7, 104 + y // 12)
        else:
            depth = y - 330
            color = (37 + depth // 13, 67 + depth // 18, 91 + depth // 24)
        draw.line((0, y, 999, y), fill=color)
    draw.ellipse((680, 185, 754, 259), fill=(227, 179, 119))
    draw.polygon(((0, 347), (115, 306), (235, 334), (395, 315), (540, 347)), fill=(49, 58, 68))
    for y in range(355, 714, 13):
        for x in range((y * 7) % 91, 1000, 107):
            draw.line((x, y, min(x + 38 + y % 31, 999), y), fill=(96, 117, 126), width=2)
    return image


def palette():
    image = Image.new("RGB", (1000, 690), (50, 47, 43))
    draw = ImageDraw.Draw(image)
    names = ["PILE 1", "WATER1", "WILLOW1", "SKY1", "WATER2", "WILLOW2", "SKY2", "DEEP", "MIDW", "LILAC"]
    colors = [(176, 112, 72), (63, 139, 169), (93, 132, 75), (119, 165, 207), (68, 113, 145),
              (111, 145, 88), (151, 178, 214), (69, 86, 118), (145, 159, 162), (165, 137, 181)]
    for i, (name, color) in enumerate(zip(names, colors)):
        x, y = (i % 4) * 250, (i // 4) * 230
        draw.rectangle((x, y + 17, x + 249, y + 229), fill=(245, 242, 230))
        draw.rectangle((x + 12, y + 30, x + 237, y + 202), fill=(26, 25, 24))
        draw.rectangle((x + 29, y + 50, x + 110, y + 157), fill=color)
        thin = tuple((c + paper) // 2 for c, paper in zip(color, (245, 242, 230)))
        draw.rectangle((x + 130, y + 72, x + 218, y + 166), fill=thin)
        for j, letter in enumerate(f"{i + 1}. {name}"):
            for dy, bits in enumerate(GLYPHS[letter]):
                for dx in range(3):
                    if int(bits) & (4 >> dx):
                        image.putpixel((x + 3 + j * 4 + dx, y + 5 + dy), (245, 242, 230))
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated bytes without writing fixtures")
    args = parser.parse_args()
    from io import BytesIO

    fixtures = [
        ("harness/delve-bot/tests/fixtures/painting.jpg", sea(), "JPEG", {"quality": 90, "subsampling": 0}),
        ("studio/fixtures/fable-palette-board.png", palette(), "PNG", {}),
    ]
    for relative, image, kind, options in fixtures:
        data = BytesIO()
        image.save(data, format=kind, **options)
        path = ROOT / relative
        if args.check:
            if path.read_bytes() != data.getvalue():
                raise SystemExit(f"Fixture differs: {relative}")
            print(f"Matches: {relative}")
        else:
            path.write_bytes(data.getvalue())
            print(f"Generated: {relative}")


if __name__ == "__main__":
    main()
